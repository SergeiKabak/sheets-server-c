-- Напоминания бота о завтрашней смене.
-- Выполнить один раз в Supabase → SQL Editor (или psql).
--
-- Сервер пишет/читает таблицу service-ключом (SUPABASE_SECRET_KEY),
-- он обходит RLS. Политик для anon нет — снаружи таблица недоступна.

create table if not exists public.reminders (
    id         bigint generated by default as identity primary key,
    chat_id    bigint      not null,
    remind_at  timestamptz not null,
    text       text        not null default '',
    sent       boolean     not null default false,
    created_at timestamptz not null default now()
);

-- Быстрый выбор созревших напоминаний фоновым циклом.
create index if not exists reminders_due_idx
    on public.reminders (remind_at)
    where not sent;

alter table public.reminders enable row level security;

