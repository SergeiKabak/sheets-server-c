-- Напоминания бота: разовые и «по графику» (начало/конец смены).
-- Выполнить один раз в Supabase → SQL Editor (или psql). Повторный запуск
-- безопасен: все объекты создаются с if not exists.
--
-- Сервер пишет/читает таблицы service-ключом (SUPABASE_SECRET_KEY),
-- он обходит RLS. Политик для anon нет — снаружи таблицы недоступны.

-- ---------------------------------------------------------------- reminders
create table if not exists public.reminders (
    id         bigint generated by default as identity primary key,
    chat_id    bigint      not null,
    kind       text        not null default 'once',  -- once | shift_start | shift_end
    remind_at  timestamptz not null,
    text       text        not null default '',
    sent       boolean     not null default false,
    created_at timestamptz not null default now()
);

-- Если таблица уже была создана ранней версией миграции — добавить колонку.
alter table public.reminders
    add column if not exists kind text not null default 'once';

-- Защита от дублей: фоновый цикл раскладывает одно и то же напоминание
-- каждый тик, повтор просто игнорируется (Prefer: ignore-duplicates).
create unique index if not exists reminders_uniq_idx
    on public.reminders (chat_id, kind, remind_at);

-- Быстрый выбор созревших напоминаний фоновым циклом.
create index if not exists reminders_due_idx
    on public.reminders (remind_at)
    where not sent;

-- ------------------------------------------------------------ reminder_subs
-- Кто включил режим «напоминать по графику» и с какими настройками.
create table if not exists public.reminder_subs (
    chat_id         bigint      primary key,
    enabled         boolean     not null default true,
    start_lead_min  int         not null default 15,  -- за сколько до начала смены
    end_delay_min   int         not null default 0,   -- через сколько после конца
    updated_at      timestamptz not null default now()
);

-- Догоняем таблицу, созданную ранней версией миграции (без настроек).
alter table public.reminder_subs
    add column if not exists start_lead_min int not null default 15;
alter table public.reminder_subs
    add column if not exists end_delay_min  int not null default 0;

alter table public.reminders     enable row level security;
alter table public.reminder_subs enable row level security;

